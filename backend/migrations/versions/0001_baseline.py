"""Baseline: the existing records, audit and sessions tables and their indexes.

Works on two kinds of SQLite database:
* a new, empty database: creates everything;
* an existing database (created by the Node backend or by the FastAPI app before Alembic):
  adopts it. Existing tables are kept exactly as they are (their columns are checked first);
  only missing tables and indexes are created. No row is read, rewritten or deleted.

On PostgreSQL the database must be empty (existing data arrives through the SQLite → PostgreSQL
transfer, ``python -m app.cli transfer-to-postgres``). PostgreSQL types: ``data`` is JSONB (must
be a JSON object), ``seq`` is an identity column that keeps insertion order (SQLite's rowid),
and the text keys use the bytewise "C" collation so ordering matches SQLite exactly. Timestamps
stay ISO-8601 UTC text (``2026-01-31T09:15:00.000Z``): the API returns them verbatim and the
business rules compare them as strings.

Revision ID: 0001_baseline
Revises:
"""
from __future__ import annotations

import sqlalchemy as sa
from alembic import op

revision = "0001_baseline"
down_revision = None
branch_labels = None
depends_on = None

EXPECTED_COLUMNS = {
    "records": {"owner", "id", "kind", "data", "revision", "updated"},
    "audit": {"id", "owner", "action", "subject", "at"},
    "sessions": {"token_hash", "workspace", "actor", "created", "expires"},
}
# Exactly the definitions already in use (Node migration + the FastAPI scaling phase), so an
# existing index is recognised by name and expression indexes still match the queries.
INDEXES = [
    "CREATE INDEX IF NOT EXISTS records_owner_kind ON records (owner, kind)",
    "CREATE INDEX IF NOT EXISTS audit_owner_at ON audit (owner, at)",
    "CREATE INDEX IF NOT EXISTS ix_records_owner_company_kind ON records (owner, json_extract(data, '$.company'), kind)",
    "CREATE INDEX IF NOT EXISTS ix_records_owner_kind_updated ON records (owner, kind, updated)",
]


POSTGRES_SCHEMA = [
    """CREATE TABLE records (
        owner TEXT COLLATE "C" NOT NULL,
        id TEXT COLLATE "C" NOT NULL,
        kind TEXT COLLATE "C" NOT NULL,
        data JSONB NOT NULL,
        revision INTEGER NOT NULL DEFAULT 1,
        updated TEXT COLLATE "C" NOT NULL,
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
        CONSTRAINT records_pkey PRIMARY KEY (owner, id),
        CONSTRAINT ux_records_seq UNIQUE (seq),
        CONSTRAINT ck_records_data_object CHECK (jsonb_typeof(data) = 'object'),
        CONSTRAINT ck_records_revision CHECK (revision >= 1)
    )""",
    """CREATE TABLE audit (
        id TEXT COLLATE "C" NOT NULL PRIMARY KEY,
        owner TEXT COLLATE "C" NOT NULL,
        action TEXT NOT NULL,
        subject TEXT NOT NULL,
        at TEXT COLLATE "C" NOT NULL,
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
        CONSTRAINT ux_audit_seq UNIQUE (seq)
    )""",
    """CREATE TABLE sessions (
        token_hash VARCHAR(64) NOT NULL PRIMARY KEY,
        workspace TEXT NOT NULL,
        actor TEXT NOT NULL,
        created TEXT NOT NULL,
        expires TEXT NOT NULL
    )""",
    "CREATE INDEX records_owner_kind ON records (owner, kind)",
    "CREATE INDEX audit_owner_at ON audit (owner, at)",
    "CREATE INDEX ix_records_owner_company_kind ON records (owner, (data ->> 'company'), kind)",
    "CREATE INDEX ix_records_owner_kind_updated ON records (owner, kind, updated)",
]


def upgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name == "postgresql":
        existing = set(sa.inspect(bind).get_table_names()) & set(EXPECTED_COLUMNS)
        if existing:
            raise RuntimeError(f"PostgreSQL database already has table(s) {sorted(existing)}; the baseline needs an empty "
                               "database. Existing data is moved with `python -m app.cli transfer-to-postgres`.")
        for statement in POSTGRES_SCHEMA:
            op.execute(statement)
        return
    inspector = sa.inspect(bind)
    existing = set(inspector.get_table_names())
    for table, expected in EXPECTED_COLUMNS.items():
        if table in existing:
            found = {column["name"] for column in inspector.get_columns(table)}
            missing = expected - found
            if missing:
                raise RuntimeError(f"Existing table '{table}' is missing column(s) {sorted(missing)}; refusing to adopt this database.")
    if "records" not in existing:
        op.create_table(
            "records",
            sa.Column("owner", sa.Text(), nullable=False),
            sa.Column("id", sa.Text(), nullable=False),
            sa.Column("kind", sa.Text(), nullable=False),
            sa.Column("data", sa.Text(), nullable=False),
            sa.Column("revision", sa.Integer(), nullable=False, server_default=sa.text("1")),
            sa.Column("updated", sa.Text(), nullable=False),
            sa.PrimaryKeyConstraint("owner", "id"),
        )
    if "audit" not in existing:
        op.create_table(
            "audit",
            sa.Column("id", sa.Text(), primary_key=True),
            sa.Column("owner", sa.Text(), nullable=False),
            sa.Column("action", sa.Text(), nullable=False),
            sa.Column("subject", sa.Text(), nullable=False),
            sa.Column("at", sa.Text(), nullable=False),
        )
    if "sessions" not in existing:
        op.create_table(
            "sessions",
            sa.Column("token_hash", sa.String(64), primary_key=True),
            sa.Column("workspace", sa.Text(), nullable=False),
            sa.Column("actor", sa.Text(), nullable=False),
            sa.Column("created", sa.Text(), nullable=False),
            sa.Column("expires", sa.Text(), nullable=False),
        )
    for statement in INDEXES:
        op.execute(statement)


def downgrade() -> None:
    raise RuntimeError("The baseline cannot be downgraded: it would drop every table and all workspace data.")
